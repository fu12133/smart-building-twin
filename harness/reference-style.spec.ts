  expect((await state()).sceneAnimation.billboard!.frame).toBe(paused.sceneAnimation.billboard!.frame);
  expect((await state()).frames).toBe(paused.frames);
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await state()).camera).toEqual(initial.camera);
  await page.getByRole('button', { name: 'Scene layers', exact: true }).click();
  await page.getByLabel('Scene animation', { exact: true }).check();
  await page.getByRole('button', { name: 'Scene layers', exact: true }).click();
  await expect.poll(async () => (await state()).sceneAnimation.billboard!.frame).toBeGreaterThan(paused.sceneAnimation.billboard!.frame);
  await page.getByRole('button', { name: '2.5D Floor', exact: true }).click(); await settled();
  const floor = await state(); await page.waitForTimeout(1100);
  expect((await state()).sceneAnimation.billboard!.frame).toBe(floor.sceneAnimation.billboard!.frame);
  expect((await state()).sceneAnimation.pedestrians!.positions).toEqual(floor.sceneAnimation.pedestrians!.positions);
  await page.getByRole('button', { name: '3D Campus', exact: true }).click(); await settled();
  expect((await state()).camera).toEqual(initial.camera);
