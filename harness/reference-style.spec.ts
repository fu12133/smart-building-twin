  expect((await page.screenshot({ clip })).equals(image), 'The one 3D advertising screen changes rendered pixels').toBe(false);
  const moved = await state();
  const distance = (a: number[], b: number[]) => Math.hypot(...a.map((v, i) => v - b[i]));
  expect(moved.sceneAnimation.pedestrians!.positions.some((p, i) => distance(p, initial.sceneAnimation.pedestrians!.positions[i]) > .2)).toBe(true);
