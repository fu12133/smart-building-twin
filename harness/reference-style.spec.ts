test('R5: Shenzhen afternoon has readable daylight ground while night and source geometry remain intact', async ({ page }) => {
  test.setTimeout(process.env.CI ? 150000 : 60000);
  let time = NIGHT_TIME;
  await page.clock.setFixedTime(time);
  await page.route(WEATHER_ROUTE, route => route.fulfill({ json: weatherFixture({ time }) }));
  await page.goto('/');
  const state = () => page.evaluate(() => window.__BUILDING_HARNESS__!());
  const settled = () => expect.poll(async () => (await state()).assetsReady, { timeout: process.env.CI ? 45000 : 20000 }).toBe(true);
  await settled(); await pauseSceneAnimation(page); await settled(); const night = await state();
  const groundLuminance = async () => {
    const image = await page.locator('.scene-host canvas').screenshot({ style: '.scene-section > :not(.scene-host), .scene-labels, .left-panels, .right-panels { visibility:hidden!important }' });
    return page.evaluate(async data => {
      const image = new Image(); image.src = 'data:image/png;base64,' + data; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
      const context = canvas.getContext('2d')!; context.drawImage(image, 0, 0);
      const pixels = context.getImageData(Math.floor(image.width * .27), Math.floor(image.height * .81), Math.floor(image.width * .12), Math.floor(image.height * .05)).data;
      let sum = 0; for (let i = 0; i < pixels.length; i += 4) sum += pixels[i] * .2126 + pixels[i + 1] * .7152 + pixels[i + 2] * .0722;
      return sum / (pixels.length / 4);
    }, image.toString('base64'));
  };
  const dark = await groundLuminance();
  time = new Date('2026-10-14T08:30:00Z'); await page.clock.setFixedTime(time);
  await page.getByRole('button', { name: '深圳天气', exact: true }).click();
  await page.getByRole('button', { name: '刷新天气', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '深圳天气详情' })).toContainText('16:30（北京时间）');
  await page.getByRole('button', { name: '关闭天气详情', exact: true }).click(); await settled();
  const bright = await groundLuminance();
  test.info().annotations.push({ type: 'Rendered ground luminance', description: `night=${dark.toFixed(2)}, afternoon=${bright.toFixed(2)}` });
  expect(bright, 'Afternoon ground has visibly higher luminance than the night presentation').toBeGreaterThan(dark * 1.3);
  expect(bright - dark).toBeGreaterThan(15);
  expect((await state()).camera).toEqual(night.camera); expect((await state()).visibleTriangles).toBe(night.visibleTriangles);
  await expect(page.locator('.clock strong')).toHaveText('16:30:00');
  await page.screenshot({ path: 'artifacts/harness/shenzhen-afternoon.png' });
});
