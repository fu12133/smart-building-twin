import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';
import { mkdirSync } from 'node:fs';

test('production assets and model interactions work under repository URL', async ({ page, baseURL }) => {
  const errors: string[] = [];
  const failures: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('response', r => { if (r.status() >= 400) failures.push(`${r.status()} ${r.url()}`); });
  const assets = ['night-city.hdr', 'project-context.glb', 'project-hospital.glb'];
  const assetResponses = Promise.all(assets.map(name => page.waitForResponse(r => r.url() === new URL('assets/' + name, baseURL!).href)));
  const weatherResponse = page.waitForResponse(r => r.url().startsWith('https://api.open-meteo.com/v1/forecast?'));
  await page.goto(baseURL!);
  for (const response of await assetResponses) expect(response.status(), response.url()).toBe(200);
  await expect(page.getByRole('heading', { name: '智慧医院综合管理平台' })).toBeVisible();
  const canvas = page.locator('.scene-host canvas');
  await expect(canvas).toBeVisible();
  // Cold public asset download/graphics initialization is separate from UI interaction latency.
  await expect(page.locator('.model-state')).toContainText('医院模型已加载', { timeout: 30000 });
  await expect(page.locator('.context-state')).toContainText('白模周边已加载', { timeout: 30000 });
  await expect(page.locator('.scene-info')).toContainText('材质与灯光方案');
  // Public verification uses actual weather, not the deterministic acceptance fixture.
  await expect(page.getByRole('button', { name: '深圳天气', exact: true })).toBeVisible();
  const response = await weatherResponse;
  expect(response.status(), 'Actual weather API status').toBe(200);
  const weatherData = await response.json();
  expect(typeof weatherData.current.temperature_2m).toBe('number');
  expect(Math.abs(Date.now() - weatherData.current.time * 1000), 'Current weather model data are fresh').toBeLessThan(90 * 60000);
  await expect(page.getByRole('button', { name: '深圳天气', exact: true })).toContainText(weatherData.current.temperature_2m.toFixed(1) + '°C');
  await page.getByRole('button', { name: '深圳天气', exact: true }).click();
  const weatherDetails = page.getByRole('dialog', { name: '深圳天气详情' });
  await expect(weatherDetails).toContainText('Open-Meteo 天气模型');
  await expect(weatherDetails).toContainText('非现场实测');
  await expect(weatherDetails).toContainText('已更新');
  await expect(weatherDetails.locator('.weather-data-time')).toContainText('北京时间');
  mkdirSync('artifacts/harness', { recursive: true });
  await page.screenshot({ path: process.env.PRODUCTION_URL ? 'artifacts/harness/weather-live-online.png' : 'artifacts/harness/weather-live-local.png' });
  await expect(page.getByLabel('北京时间')).toBeVisible();
  await page.getByRole('button', { name: '关闭天气详情' }).click();
  await expect(page.getByRole('button', { name: '选择A区' })).toBeVisible();
  expect(await page.evaluate(() => typeof (window as any).__BUILDING_HARNESS__)).toBe('undefined');
  const rect = (await canvas.boundingBox())!;
  const before = await canvas.screenshot();
  await page.mouse.move(rect.x + rect.width * .48, rect.y + rect.height * .55);
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .7, rect.y + rect.height * .6, { steps: 20 });
  await page.mouse.up();
  const after = await canvas.screenshot();
  expect(createHash('sha256').update(after).digest('hex')).not.toBe(createHash('sha256').update(before).digest('hex'));
  await page.getByRole('button', { name: '复位视角' }).click();
  // Production has no diagnostics: allow the bounded software render queue to present the exact pose.
  await page.waitForTimeout(1000);
  mkdirSync('artifacts/harness', { recursive: true });
  await page.screenshot({ path: process.env.PRODUCTION_URL ? 'artifacts/harness/source-context-online-default.png' : 'artifacts/harness/source-context-production-default.png' });
  const sourceDefault = createHash('sha256').update(await canvas.screenshot()).digest('hex');
  await page.getByRole('button', { name: '查看完整白模', exact: true }).click();
  await page.waitForTimeout(1000);
  const sourceFull = createHash('sha256').update(await canvas.screenshot()).digest('hex');
  expect(sourceFull, 'Full source view changes actual rendered geometry').not.toBe(sourceDefault);
  await page.screenshot({ path: process.env.PRODUCTION_URL ? 'artifacts/harness/source-context-online-full.png' : 'artifacts/harness/source-context-production-full.png' });
  await page.getByRole('button', { name: '复位视角' }).click();
  await page.getByRole('button', { name: '2.5D 楼层' }).click();
  await page.getByRole('button', { name: '选择设备 空调机组' }).click();
  await expect(page.getByRole('dialog', { name: '设备详情' })).toContainText('AC-01');
  await page.getByRole('button', { name: '关闭设备详情' }).click();
  const floorCapture = () => canvas.screenshot({ style: '.scene-section > :not(.scene-host), .scene-labels, .left-panels, .right-panels { visibility: hidden !important; }' });
  const secondFloor = createHash('sha256').update(await floorCapture()).digest('hex');
  await page.getByLabel('选择楼层').selectOption('1');
  await expect(page.getByLabel('楼层布局说明')).toContainText('方案示意');
  const firstFloor = createHash('sha256').update(await floorCapture()).digest('hex');
  expect(firstFloor, 'Production floors have different actual geometry').not.toBe(secondFloor);
  await page.getByRole('button', { name: '选择设备 通道摄像机', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '设备详情' })).toContainText('A-1F-CAM-02');
  await expect(page.getByRole('dialog', { name: '设备详情' })).toContainText('西侧分区 1');
  await page.getByRole('button', { name: '关闭设备详情' }).click();
  await page.getByRole('button', { name: '切换到 13F', exact: true }).click();
  await expect(page.locator('.scene-info')).toContainText('保留原有功能');
  await page.getByRole('button', { name: '筛选给排水', exact: true }).click();
  await expect(page.locator('.device-pin:visible')).toHaveCount(1);
  await page.getByRole('button', { name: '选择设备 给排水监测器', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '设备详情' })).toContainText('A-13F-WTR-05');
  await page.getByRole('button', { name: '关闭设备详情' }).click();
  await page.getByRole('button', { name: '显示全部设备' }).click();
  await expect(page.locator('.device-pin:visible')).toHaveCount(6);
  mkdirSync('artifacts/harness', { recursive: true });
  await page.screenshot({ path: process.env.PRODUCTION_URL ? 'artifacts/harness/interior-online.png' : 'artifacts/harness/interior-production-local.png' });
  await page.getByRole('button', { name: '3D 院区' }).click();
  await page.getByRole('button', { name: '能源分析', exact: true }).click();
  await expect(page.getByRole('heading', { name: '今日用电趋势' })).toBeVisible();
  await page.getByRole('button', { name: '院区总览', exact: true }).click();
  await page.waitForTimeout(1200); // Let ECharts' entrance animation finish before capturing evidence.
  mkdirSync('artifacts/harness', { recursive: true });
  await page.screenshot({ path: process.env.PRODUCTION_URL ? 'artifacts/harness/production-online.png' : 'artifacts/harness/production-local.png' });
  expect(errors, 'Production console errors').toEqual([]);
  expect(failures, 'Production asset HTTP failures').toEqual([]);
});
